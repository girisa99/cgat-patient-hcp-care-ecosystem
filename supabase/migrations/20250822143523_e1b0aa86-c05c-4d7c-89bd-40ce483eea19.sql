-- RLS Policies
-- Node Analytics
CREATE POLICY "Users can view their own node analytics" ON public.node_analytics
  FOR SELECT USING (auth.uid() IS NOT NULL);

CREATE POLICY "System can insert node analytics" ON public.node_analytics
  FOR INSERT WITH CHECK (true);

CREATE POLICY "System can update node analytics" ON public.node_analytics
  FOR UPDATE USING (true);

-- Node Usage Events
CREATE POLICY "Users can view their own usage events" ON public.node_usage_events
  FOR SELECT USING (user_id = auth.uid() OR auth.uid() IS NOT NULL);

CREATE POLICY "Users can create usage events" ON public.node_usage_events
  FOR INSERT WITH CHECK (user_id = auth.uid());

-- Node Suggestions
CREATE POLICY "Users can view their own suggestions" ON public.node_suggestions
  FOR SELECT USING (user_id = auth.uid());

CREATE POLICY "Users can manage their own suggestions" ON public.node_suggestions
  FOR ALL USING (user_id = auth.uid());

-- Node Config Templates
CREATE POLICY "Users can view active templates" ON public.node_config_templates
  FOR SELECT USING (is_active = true);

CREATE POLICY "Users can create their own templates" ON public.node_config_templates
  FOR INSERT WITH CHECK (created_by = auth.uid());

CREATE POLICY "Users can update their own templates" ON public.node_config_templates
  FOR UPDATE USING (created_by = auth.uid() OR is_system_template = false);

-- Workflow Analysis
CREATE POLICY "Users can view their own workflow analysis" ON public.workflow_analysis
  FOR SELECT USING (user_id = auth.uid());

CREATE POLICY "Users can create workflow analysis" ON public.workflow_analysis
  FOR INSERT WITH CHECK (user_id = auth.uid());


-- Create tables for Node Insights functionality

-- Node analytics for tracking usage and performance
CREATE TABLE IF NOT EXISTS public.node_analytics (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  node_type TEXT NOT NULL,
  workflow_id UUID,
  node_id TEXT,
  usage_count INTEGER DEFAULT 0,
  success_count INTEGER DEFAULT 0,
  failure_count INTEGER DEFAULT 0,
  total_execution_time_ms BIGINT DEFAULT 0,
  average_execution_time_ms INTEGER DEFAULT 0,
  user_rating DECIMAL(3,2) DEFAULT 0.0,
  common_connections JSONB DEFAULT '[]'::jsonb,
  performance_metrics JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Node usage events for detailed tracking
CREATE TABLE IF NOT EXISTS public.node_usage_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  node_type TEXT NOT NULL,
  node_id TEXT NOT NULL,
  workflow_id UUID,
  user_id UUID REFERENCES auth.users(id),
  action TEXT NOT NULL CHECK (action IN ('created', 'configured', 'executed', 'removed', 'modified')),
  execution_time_ms INTEGER,
  success BOOLEAN,
  error_details JSONB,
  metadata JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Node suggestions generated by AI analysis
CREATE TABLE IF NOT EXISTS public.node_suggestions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  workflow_id UUID,
  user_id UUID REFERENCES auth.users(id),
  node_type TEXT NOT NULL,
  suggestion_type TEXT NOT NULL CHECK (suggestion_type IN ('next_node', 'optimization', 'best_practice', 'connection')),
  title TEXT NOT NULL,
  description TEXT,
  priority TEXT DEFAULT 'medium' CHECK (priority IN ('low', 'medium', 'high', 'critical')),
  confidence_score DECIMAL(3,2) DEFAULT 0.0,
  config_template JSONB DEFAULT '{}'::jsonb,
  dependencies JSONB DEFAULT '[]'::jsonb,
  implementation_notes TEXT,
  is_applied BOOLEAN DEFAULT false,
  applied_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  expires_at TIMESTAMP WITH TIME ZONE
);

-- Node configuration templates for different node types
CREATE TABLE IF NOT EXISTS public.node_config_templates (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  node_type TEXT NOT NULL,
  template_name TEXT NOT NULL,
  description TEXT,
  category TEXT DEFAULT 'general',
  config_schema JSONB NOT NULL DEFAULT '{}'::jsonb,
  default_config JSONB NOT NULL DEFAULT '{}'::jsonb,
  validation_rules JSONB DEFAULT '{}'::jsonb,
  is_system_template BOOLEAN DEFAULT false,
  is_active BOOLEAN DEFAULT true,
  created_by UUID REFERENCES auth.users(id),
  usage_count INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  UNIQUE(node_type, template_name)
);

-- Workflow analysis results
CREATE TABLE IF NOT EXISTS public.workflow_analysis (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  workflow_id UUID NOT NULL,
  user_id UUID REFERENCES auth.users(id),
  analysis_type TEXT NOT NULL CHECK (analysis_type IN ('performance', 'optimization', 'suggestions', 'validation')),
  current_nodes JSONB NOT NULL DEFAULT '[]'::jsonb,
  analysis_results JSONB NOT NULL DEFAULT '{}'::jsonb,
  suggestions_generated INTEGER DEFAULT 0,
  performance_score DECIMAL(3,2) DEFAULT 0.0,
  complexity_score DECIMAL(3,2) DEFAULT 0.0,
  optimization_opportunities JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);


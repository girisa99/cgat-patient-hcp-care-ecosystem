-- Create trigger for updating node analytics
CREATE OR REPLACE FUNCTION update_node_analytics()
RETURNS TRIGGER AS $$
BEGIN
  -- Update or insert analytics based on usage events
  INSERT INTO public.node_analytics (node_type, node_id, workflow_id, usage_count, success_count, failure_count)
  VALUES (NEW.node_type, NEW.node_id, NEW.workflow_id, 1, 
          CASE WHEN NEW.success = true THEN 1 ELSE 0 END,
          CASE WHEN NEW.success = false THEN 1 ELSE 0 END)
  ON CONFLICT (node_type, COALESCE(node_id, ''), COALESCE(workflow_id::text, ''))
  DO UPDATE SET
    usage_count = node_analytics.usage_count + 1,
    success_count = node_analytics.success_count + CASE WHEN NEW.success = true THEN 1 ELSE 0 END,
    failure_count = node_analytics.failure_count + CASE WHEN NEW.success = false THEN 1 ELSE 0 END,
    total_execution_time_ms = node_analytics.total_execution_time_ms + COALESCE(NEW.execution_time_ms, 0),
    average_execution_time_ms = CASE 
      WHEN node_analytics.usage_count > 0 THEN 
        (node_analytics.total_execution_time_ms + COALESCE(NEW.execution_time_ms, 0)) / (node_analytics.usage_count + 1)
      ELSE COALESCE(NEW.execution_time_ms, 0)
    END,
    updated_at = now();
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Add unique constraint to node_analytics for proper conflict resolution
ALTER TABLE public.node_analytics ADD CONSTRAINT unique_node_analytics 
  UNIQUE (node_type, COALESCE(node_id, ''), COALESCE(workflow_id::text, ''));

-- Create trigger
CREATE TRIGGER update_node_analytics_trigger
  AFTER INSERT ON public.node_usage_events
  FOR EACH ROW EXECUTE FUNCTION update_node_analytics();

-- Create trigger for updating updated_at timestamps
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_node_analytics_updated_at
  BEFORE UPDATE ON public.node_analytics
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER update_node_config_templates_updated_at
  BEFORE UPDATE ON public.node_config_templates
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
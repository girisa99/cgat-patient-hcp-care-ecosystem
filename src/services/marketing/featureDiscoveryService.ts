/**
 * Feature Discovery Service
 * 
 * Automatically detects and registers new features, pipelines, and categories
 * for the dogfooding marketing engine. Configurable for custom messaging.
 */

import { PIPELINE_MARKETING_CATALOG, CATEGORY_METADATA, type PipelineCategory, type ContentFormat } from '../marketingContentManager';
import { GENIE_PRODUCT_POSITIONING, FEATURE_SHOWCASE_TOPICS } from '../dogfoodingMarketingEngine';

// ============================================================================
// TYPES
// ============================================================================

export interface DiscoveredFeature {
  id: string;
  name: string;
  category: PipelineCategory;
  product: string;
  discoveredAt: Date;
  status: 'new' | 'pending_messaging' | 'active' | 'deprecated';
  
  // Auto-generated messaging
  autoGeneratedHook?: string;
  autoGeneratedDescription?: string;
  
  // Custom messaging (overrides auto-generated)
  customMessaging?: CustomMessaging;
  
  // Stats
  timesUsed: number;
  lastUsed?: Date;
  performanceScore?: number;
}

export interface CustomMessaging {
  headline: string;
  hook: string;
  description: string;
  painPoints?: string[];
  benefits?: string[];
  targetAudience?: string[];
  hashtags?: string[];
  avoidWords?: string[];
}

export interface FeatureCategory {
  id: PipelineCategory;
  name: string;
  features: DiscoveredFeature[];
  isActive: boolean;
  customMessaging?: Partial<CustomMessaging>;
  priority: number;
  rotationWeight: number; // 0-100, higher = more frequent in marketing
}

export interface MessagingTemplate {
  id: string;
  name: string;
  type: 'headline' | 'hook' | 'body' | 'cta';
  template: string; // Uses placeholders like {{feature_name}}, {{benefit}}
  category?: PipelineCategory;
  format?: ContentFormat;
  region?: string;
  usageCount: number;
  performanceScore?: number;
}

export interface PositioningStatement {
  id: string;
  product: string;
  region: string;
  statement: string;
  isActive: boolean;
  createdAt: Date;
  lastUsed?: Date;
}


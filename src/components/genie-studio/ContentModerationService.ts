/**
 * Get safety level label
 */
export function getSafetyLabel(score: number): { label: string; color: string } {
  if (score >= 90) return { label: 'Safe', color: 'text-green-600' };
  if (score >= 70) return { label: 'Caution', color: 'text-yellow-600' };
  if (score >= 50) return { label: 'Warning', color: 'text-orange-600' };
  return { label: 'Blocked', color: 'text-red-600' };
}

/**
 * Get all pipelines supporting a specific vertical
 */
export function getPipelinesByVertical(vertical: ProductVertical): PipelineCapabilityEntry[] {
  return PIPELINE_CAPABILITY_MATRIX.filter(
    p => p.verticalSupport[vertical] === 'full' || p.verticalSupport[vertical] === 'partial'
  );
}

/**
 * Get all pipelines for a specific category
 */
export function getPipelinesByCategory(category: PipelineCategory): PipelineCapabilityEntry[] {
  return PIPELINE_CAPABILITY_MATRIX.filter(p => p.category === category);
}

/**
 * Get all pipelines supported by a specific provider
 */
export function getPipelinesByProvider(providerId: ProviderId): PipelineCapabilityEntry[] {
  return PIPELINE_CAPABILITY_MATRIX.filter(
    p => p.primaryProviders.includes(providerId) || p.fallbackProviders.includes(providerId)
  );
}

/**
 * Get all pipelines available at a specific tier
 */
export function getPipelinesByTier(tier: PricingTier): PipelineCapabilityEntry[] {
  const tierOrder: PricingTier[] = ['free', 'starter', 'pro', 'enterprise'];
  const tierIndex = tierOrder.indexOf(tier);
  return PIPELINE_CAPABILITY_MATRIX.filter(
    p => tierOrder.indexOf(p.minimumTier) <= tierIndex
  );
}

/**
 * Get summary statistics for the capability matrix
 */
export function getPipelineMatrixSummary() {
  const totalPipelines = PIPELINE_CAPABILITY_MATRIX.length;
  
  const byCategory = PIPELINE_CAPABILITY_MATRIX.reduce((acc, p) => {
    acc[p.category] = (acc[p.category] || 0) + 1;
    return acc;
  }, {} as Record<string, number>);
  
  const byTier = PIPELINE_CAPABILITY_MATRIX.reduce((acc, p) => {
    acc[p.minimumTier] = (acc[p.minimumTier] || 0) + 1;
    return acc;
  }, {} as Record<string, number>);
  
  const averageQuality = PIPELINE_CAPABILITY_MATRIX.reduce((sum, p) => sum + p.qualityScore, 0) / totalPipelines;
  const averageAutomation = PIPELINE_CAPABILITY_MATRIX.reduce((sum, p) => sum + p.automationLevel, 0) / totalPipelines;
  
  return {
    totalPipelines,
    byCategory,
    byTier,
    averageQuality: Math.round(averageQuality),
    averageAutomation: Math.round(averageAutomation),
  };
}


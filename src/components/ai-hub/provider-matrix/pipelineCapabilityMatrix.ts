// ============================================
// PRODUCT VERTICALS (Column Headers)
// ============================================
export type ProductVertical =
  | 'presentations'      // Slide decks, pitch decks, training decks
  | 'ai_avatar'          // AI Avatar video generation
  | 'generative_video'   // Text/Image to video, animations
  | 'video_repurposing'  // Long-to-short, video editing
  | 'social_publishing'  // TikTok, Reels, YouTube, LinkedIn
  | 'ld_training'        // L&D, SCORM, compliance training
  | 'marketing_ads'      // Ads, campaigns, promotional content
  | 'localization'       // Multi-language dubbing, translation
  | 'enterprise'         // SSO, compliance, API access
  | 'data_analytics'     // Data visualization, reports
  | 'internal_comms'     // Town halls, announcements
  | 'customer_education' // Help videos, onboarding
  | 'sales_enablement'   // Demo videos, proposals
  | 'live_realtime';     // Live streaming, real-time

// ============================================
// PRICING TIERS
// ============================================
export type PricingTier = 'free' | 'starter' | 'pro' | 'enterprise';

// ============================================
// CAPABILITY SUPPORT LEVEL
// ============================================
export type SupportLevel = 
  | 'full'       // Fully supported
  | 'partial'    // Partially supported
  | 'planned'    // On roadmap
  | 'none';      // Not supported

// ============================================
// PIPELINE CAPABILITY ENTRY
// ============================================
export interface PipelineCapabilityEntry {
  pipelineId: string;
  displayName: string;
  description: string;
  category: PipelineCategory;
  
  // Product vertical support
  verticalSupport: Record<ProductVertical, SupportLevel>;
  
  // Provider support
  primaryProviders: ProviderId[];
  fallbackProviders: ProviderId[];
  
  // Tier requirements
  minimumTier: PricingTier;
  recommendedTier: PricingTier;
  
  // Capabilities required
  requiredCapabilities: string[];
  optionalCapabilities: string[];
  
  // Rich content considerations
  richContentFeatures: RichContentFeature[];
  previewSupport: PreviewSupport;
  
  // Metrics
  estimatedDurationSeconds: number;
  qualityScore: number; // 0-100
  automationLevel: number; // 0-100 (how automated vs manual)
}

